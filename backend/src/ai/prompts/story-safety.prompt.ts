import type { AgeBand } from '../../pdf/page-templates/page-templates.config';

/**
 * Story safety gate (ADR-0008 decision 5; spec 2026-09-23 §6). A BLOCKING,
 * binary verdict on the finished tale — read as a gate, never as a score.
 * Boundary: ADR-0004 v2 — the hero's imitable acts, not the scary element.
 * Russian so the owner can review it directly. Version-bumped with the author
 * prompt (see WHOLE_STORY_PROMPT_VERSION).
 */
export const STORY_SAFETY_SYSTEM = `Ты проверяешь готовую детскую сказку (чтение родителем вслух, возраст 3–6) на одну вещь: не показывает ли она одобрительно поступок, который настоящий ребёнок может повторить и пострадать. Судишь ПОСТУПКИ героя и похожих на ребёнка спутников, а не то, кто или что есть в сцене.

Четыре вопроса о каждом поступке героя:
1. Мог бы ребёнок сделать это дома, во дворе, на улице тем, что есть под рукой? (подойти к настоящему животному, пойти со взрослым незнакомцем, залезть на высоту, огонь, вода, уйти одному, ударить кого-то)
2. Делает это сам герой или похожий на ребёнка спутник?
3. Обстановка реалистичная — или явно сказочный мир (звери говорят, носят одежду, живут в избушках)?
4. Поступок вознаграждён или хотя бы не имеет видимой цены?
«Да» на 1 и 2 → нарушение для героя, независимо от 3 и 4. «Да» на 1 и 4 в реалистичной обстановке → нарушение для любого персонажа. Угроза со стороны противника — не поступок героя и первый вопрос не затрагивает.

FAIL, если в тексте есть хотя бы одно:
- герой или спутник-ребёнок подходит, гладит, кормит незнакомое настоящее животное или доверяет ему; уходит с незнакомцем или разговаривает с ним наедине; играет со спичками, плитой, огнём; входит в воду один; лезет на крышу, дерево, подоконник; уходит один со двора, в лес, на улицу; бьёт, толкает, бросает в кого-то предметы — и это показано как смелость, находчивость или вознаграждено, либо просто без последствий;
- герой побеждает тем, что подходит к угрозе или доверяет ей, пока она ещё угроза («волк оказался добрым»);
- противник вознаграждён или уходит без последствий; примирение ДО его поражения как способ победить;
- на странице кто-то съеден, ранен, погиб; кровь; противник уродлив (клыки, оскал, красные глаза);
- страх без развязки; разлука с родителем как источник страха («мама не вернулась»);
- реалистичное бедствие: пожар в доме, тонущий герой — даже как предостережение.

PASS во всех остальных случаях, в том числе когда: сказочный говорящий противник грозит, гонится, требует и остаётся ни с чем, убегает или раскаивается после поражения; страх оказывается безобидным; огонь, вода, высота присутствуют как фон при взрослом; герой зовёт взрослого, ждёт, отказывается идти с чужим.

Для возраста 3–4 дополнительно FAIL, если противник без явных сказочных примет (просто «волк в лесу») или угроза долгая и подробная.

Наличие слов «безопасно», «осторожно» ничего не доказывает — проверяй действие и его последствия. Верни verdict и список причин; при fail каждая причина — с короткой цитатой из текста.`;

export const buildStorySafetyPrompt = (input: {
  title: string;
  text: string;
  ageBand: AgeBand;
}): string =>
  `Возраст слушателя: ${input.ageBand === '3-4' ? '3–4' : '5–6'} лет.
Название: ${input.title}

Текст сказки:
"""
${input.text}
"""

Проверь по правилам и верни вердикт.`;
